-- November 2026 WhatsApp campaign audit and deduplication.
-- Apply through the Neon migration workflow; do not run ad hoc in production.

CREATE TABLE whatsapp_campaign_sends (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_key text NOT NULL,
  prospect_id bigint NOT NULL REFERENCES prospects(id) ON DELETE RESTRICT,
  phone text NOT NULL,
  template_name text NOT NULL,
  consent_source text NOT NULL,
  status text NOT NULL CHECK (
    status IN ('reserved', 'accepted', 'held', 'failed')
  ),
  provider_message_id text,
  error_code text,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (campaign_key, phone)
);

CREATE INDEX idx_whatsapp_campaign_sends_prospect
  ON whatsapp_campaign_sends (prospect_id, created_at DESC);

CREATE INDEX idx_whatsapp_campaign_sends_status
  ON whatsapp_campaign_sends (campaign_key, status);
